@RunWith(AndroidJUnit4::class)
class UpdateAndNovelSettingsTest {
    @get:Rule val compose = createAndroidComposeRule<MainActivity>()
    private fun release(version: String = "1.0.0", repository: String = "pieyixi/Pawchive-APK"): String {
        val names = listOf("Pawchive-$version.apk", "SHA256SUMS.txt")
        return JSONObject().put("tag_name", "v$version").put("assets", JSONArray(names.map { name -> JSONObject().put("name", name).put("browser_download_url", "https://github.com/$repository/releases/download/v$version/$name") })).toString()
    }
    @Test fun updateVersionsAreNumericAndAssetsBelongToThisRepository() {
        assertTrue(newerVersion("0.1.10", "0.1.9")); assertFalse(newerVersion("0.1.9", "0.1.10")); assertFalse(newerVersion("0.1.10", "0.1.10"))
        assertEquals("1.0.0", parseUpdateRelease(release()).version)
        assertThrows(IllegalArgumentException::class.java) { parseUpdateRelease(release(repository = "other/repo")) }
    }
    @Test fun corruptedUpdateIsRejectedBeforeInstallation(): Unit = runBlocking {
        val application = compose.activity.application as PawApplication
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
        val client = OkHttpClient.Builder().addInterceptor { chain ->
            val body = when {
                chain.request().url.host == "api.github.com" -> release()
                chain.request().url.encodedPath.endsWith("SHA256SUMS.txt") -> "${"f".repeat(64)}  Pawchive-1.0.0.apk"
                else -> "corrupt fixture"
            }
            Response.Builder().request(chain.request()).protocol(Protocol.HTTP_1_1).code(200).message("OK").body(body.toResponseBody("application/octet-stream".toMediaType())).build()
        }.build()
        try {
            val updater = AppUpdater(application, scope, client)
            updater.check()
            withTimeout(10000) { updater.state.first { !it.busy } }
            assertNotNull(updater.state.value.release)
            updater.download()
            val result = withTimeout(10000) { updater.state.first { !it.busy } }
            assertNull(result.ready); assertTrue(result.message.contains("校验失败"))
            assertTrue(java.io.File(application.cacheDir, "updates").listFiles().orEmpty().none { it.name.endsWith(".partial.apk") })
        } finally { scope.cancel() }
    }
    @Test fun signedNewerUpdateDownloadsAndCanBeReadThroughPrivateProvider(): Unit = runBlocking {
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val fixture = runCatching { instrumentation.context.assets.open("update-fixture.apk").use { it.readBytes() } }.getOrNull()
        org.junit.Assume.assumeTrue("Local signed update fixture is generated by qa/build-update-fixture.ps1", fixture != null)
        val bytes = fixture!!
        val digest = java.security.MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        val application = compose.activity.application as PawApplication
        val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
        val client = OkHttpClient.Builder().addInterceptor { chain ->
            val body = when {
                chain.request().url.host == "api.github.com" -> release("0.1.12").toByteArray()
                chain.request().url.encodedPath.endsWith("SHA256SUMS.txt") -> "$digest  Pawchive-0.1.12.apk".toByteArray()
                else -> bytes
            }
            Response.Builder().request(chain.request()).protocol(Protocol.HTTP_1_1).code(200).message("OK").body(body.toResponseBody("application/octet-stream".toMediaType())).build()
        }.build()
        val finalFile = java.io.File(application.cacheDir, "updates/Pawchive-0.1.12.apk")
        try {
            val updater = AppUpdater(application, scope, client)
            updater.check(); withTimeout(10000) { updater.state.first { !it.busy } }
            updater.download()
            val result = withTimeout(10000) { updater.state.first { !it.busy } }
            assertNotNull(result.message, result.ready)
            val uri = androidx.core.content.FileProvider.getUriForFile(application, "${application.packageName}.updates", result.ready!!)
            assertEquals("content", uri.scheme)
            application.contentResolver.openInputStream(uri)!!.use { assertArrayEquals(bytes, it.readBytes()) }
            assertFalse(application.packageManager.getProviderInfo(android.content.ComponentName(application, androidx.core.content.FileProvider::class.java), 0).exported)
        } finally { scope.cancel(); finalFile.delete() }
    }
    @Test fun novelSwitchPersistsAcrossRecreationAndCheckUpdateIsBelowVersion(): Unit = runBlocking {
        val repo = (compose.activity.application as PawApplication).container.repository
        val previous = repo.hideSuspectedNovels.first()
        try {
            repo.setHideSuspectedNovels(false)
            compose.onNodeWithText("我的").performClick()
            compose.onNodeWithText("设置").performClick()
            compose.onNodeWithTag("settings_novel_switch").assertIsOff().performClick()
            withTimeout(5000) { repo.hideSuspectedNovels.first { it } }
            compose.onNodeWithTag("settings_novel_switch").assertIsOn()
            val version = compose.onNodeWithText(BuildConfig.VERSION_NAME).fetchSemanticsNode().boundsInRoot
            val check = compose.onNodeWithTag("settings_check_update").fetchSemanticsNode().boundsInRoot
            assertTrue(check.top >= version.bottom)
            compose.activityRule.scenario.recreate()
            compose.waitForIdle()
            compose.onNodeWithTag("settings_novel_switch").assertIsOn()
            compose.onNodeWithTag("settings_check_update").performClick()
            compose.waitUntil(20000) { compose.onAllNodesWithText("已是最新版本").fetchSemanticsNodes().isNotEmpty() }
        } finally { repo.setHideSuspectedNovels(previous) }
    }
    @Test fun globalAscendingUsesOldestServerPageAndContinues(): Unit = runBlocking {
        val repo = (compose.activity.application as PawApplication).container.repository
        val filters = SearchFilters(workOrder = "asc", media = "video")
        val first = withTimeout(25000) { repo.searchWorkPage("JK", 0, false, filters, true) }
        assertTrue(first.rawPosts.isNotEmpty()); assertTrue(first.more)
        val second = withTimeout(20000) { repo.searchWorkPage("JK", first.nextOffset, false, filters, false) }
        assertTrue(first.rawPosts.none { a -> second.rawPosts.any { a.key == it.key } })
        assertEquals(first.nextOffset - 50, second.nextOffset)
        compose.onNodeWithText("作品").performClick()
        compose.onNode(hasSetTextAction()).performTextReplacement("JK")
        compose.onNodeWithContentDescription("高级搜索").performClick()
        compose.onNodeWithTag("filter_media_video").performClick()
        compose.onNodeWithTag("filter_work_order_asc").performClick()
        compose.onNodeWithTag("filter_apply").performClick()
        val oldestTitle = first.rawPosts.first().title
        compose.waitUntil(25000) { compose.onAllNodesWithText(oldestTitle).fetchSemanticsNodes().isNotEmpty() }
        compose.onNodeWithContentDescription("高级搜索").performClick()
        compose.onNodeWithTag("filter_work_order_asc").assertIsSelected()
        compose.onNodeWithTag("filter_work_order_desc").performClick()
        compose.onNodeWithTag("filter_apply").performClick()
        val latest = repo.api.posts(filters.copy(workOrder = "desc").workQuery("JK")).first().title
        compose.waitUntil(20000) { compose.onAllNodesWithText(latest).fetchSemanticsNodes().isNotEmpty() }
    }
}
